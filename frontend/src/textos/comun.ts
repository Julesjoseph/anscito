const MESES: Record<string, [string, string, string]> = { Enero: ['January', 'Janvier', 'Janvye'], Febrero: ['February', 'Février', 'Fevriye'], Marzo: ['March', 'Mars', 'Mas'], Abril: ['April', 'Avril', 'Avril'], Mayo: ['May', 'Mai', 'Me'], Junio: ['June', 'Juin', 'Jen'], Julio: ['July', 'Juillet', 'Jiyè'], Agosto: ['August', 'Août', 'Out'], Septiembre: ['September', 'Septembre', 'Septanm'], Octubre: ['October', 'Octobre', 'Oktòb'], Noviembre: ['November', 'Novembre', 'Novanm'], Diciembre: ['December', 'Décembre', 'Desanm'] }
// Mes en otro idioma (0 inglés, 1 francés, 2 kreyòl); si no es un mes, igual.
export const mes = (m: string, i: number) => MESES[m[0].toUpperCase() + m.slice(1)]?.[i] ?? m

